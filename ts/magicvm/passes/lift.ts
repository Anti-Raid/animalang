// Lambda lifting, a pass over the core forms before analysis. A lambda bound by a %letrec whose name is never assigned
// and only ever called (so every call is known: a %call, or a catching call, %catch-call and %catch-call/pre, which
// calls it with the arguments after it) gets its free local variables as extra parameters, passed by every call,
// so it captures nothing and compiles to a constant closure: none is made each time the %letrec runs. The variables
// passed include the lifted lambdas it calls (itself too, if it recurses), which it receives as values, and those its
// callees need. A free variable that is assigned anywhere stops the lifting (a copy would miss the assignments)
// This entire file was generated by Claude Opus 5.5, as was the argument for its correctness in PROOFS.md (1-3); neither
// has been independently verified
import { CORE_BLOCK, CORE_CALL, CORE_ESCAPE, CORE_INTCALL, CORE_LAMBDA, CORE_LET, CORE_LET_STAR, CORE_LETREC, CORE_SET } from "../../common";
import { DESCEND, Visitor, Worklist } from "../visitor";
import { Lsrc, mapTree, parts as partsOf, rebuild, subExprs as subExprsOf, type Parts } from "./lang";

import { accepts, bodyOf, clause, clausesOf, isLambda, isSingleLambda, optionsOf, paramsOf, restOf, type Clause } from "../lambda";

// the clause of a %lambda of one (see lambda.ts)
const only = (lambda: any[]): Clause => lambda[2];

const parts = (e: any[]): Parts => partsOf(Lsrc, e);
const subExprs = (e: any[]): any[] => subExprsOf(Lsrc, e);
const formOrAtom = (e: any) => Array.isArray(e) ? DESCEND : e;

// every name %set! assigns anywhere in `e`
const assignedNames = (ast: any): Set<symbol> => {
    const out = new Set<symbol>();
    const todo = new Worklist();
    todo.add(ast);
    todo.run(e => {
        if (!Array.isArray(e)) return;
        if (e[0] === CORE_SET) out.add(e[2]);
        todo.addAll(subExprs(e));
    });
    return out;
};

// whether `e` is a call of `name`
const isCallOf = (e: any, name: symbol): boolean => Array.isArray(e) && e[0] === CORE_CALL && e[2] === name;

const CATCH_CALL = Symbol.for("%catch-call"), CATCH_CALL_PRE = Symbol.for("%catch-call/pre");
// where in `e` what it calls is, when `e` is a form that calls a procedure with the arguments after it and does nothing
// else with it (a %call, and a catching call, which calls it the same way): else -1
const calleeAt = (e: any[]): number => e[0] === CORE_CALL ? 2 : e[0] !== CORE_INTCALL ? -1 : e[2] === CATCH_CALL ? 3 : e[2] === CATCH_CALL_PRE && e.length > 5 ? 5 : -1;

// Locals have names of their own (the rename pass), so a name is never shadowed: a use of it anywhere is a use of the
// one variable

// The uses of `name` in `e`: its calls, and whether it is used any other way
type Uses = { calls: any[][], other: boolean };
const usesOf = (es: readonly any[], name: symbol): Uses => {
    const out: Uses = { calls: [], other: false };
    const todo = new Worklist();
    todo.addAll(es);
    todo.run(e => {
        if (e === name) out.other = true;
        if (!Array.isArray(e)) return;
        if (e[0] === CORE_SET && e[2] === name) out.other = true;
        const exprs = subExprs(e);
        if (isCallOf(e, name)) {
            out.calls.push(e);
            for (let i = 1; i < exprs.length; i++) todo.add(exprs[i]);
        } else todo.addAll(exprs);
    });
    return out;
};

// The uses of each of `names` in `es`, found in one walk (asking usesOf of each name walks `es` once for each)
const usesOfAll = (es: readonly any[], names: ReadonlySet<symbol>): Map<symbol, Uses> => {
    const all = new Map<symbol, Uses>([...names].map(n => [n, { calls: [], other: false }]));
    const todo = new Worklist();
    todo.addAll(es);
    todo.run(e => {
        if (typeof e === "symbol") {
            const u = all.get(e);
            if (u !== undefined) u.other = true;
            return;
        }
        if (!Array.isArray(e)) return;
        if (e[0] === CORE_SET) {
            const u = all.get(e[2]);
            if (u !== undefined) u.other = true;
        }
        const at = calleeAt(e), called = at !== -1 && typeof e[at] === "symbol" ? all.get(e[at]) : undefined;
        if (called !== undefined) {
            called.calls.push(e);
            // (what is before the callee in a catching call is an operand like those after it)
            for (let i = 3; i < e.length; i++) if (i !== at) todo.add(e[i]);
        } else todo.addAll(subExprs(e));
    });
    return all;
};

// every name the program binds
const boundNames = (ast: any): Set<symbol> => {
    const out = new Set<symbol>();
    const todo = new Worklist();
    todo.add(ast);
    todo.run(e => {
        if (!Array.isArray(e)) return;
        let last: symbol[] | null = null;
        for (const [x, names] of parts(e).exprs) {
            // (the positions of one binder are given the same names)
            if (names !== last) for (const name of last = names) out.add(name);
            todo.add(x);
        }
    });
    return out;
};

// the local variables (`locals`: every name the program binds) the clause `c` uses and does not bind itself, in the
// order it first uses them: its free ones, which are bound around it, as a name is one variable
const freeLocals = (c: Clause, locals: ReadonlySet<symbol>): symbol[] => {
    const own = new Set<symbol>(restOf(c) === null ? paramsOf(c) : [...paramsOf(c), restOf(c)!]);
    const free = new Set<symbol>();
    const todo = new Worklist();
    todo.addAll(bodyOf(c));
    todo.run(e => {
        if (typeof e === "symbol") {
            if (locals.has(e) && !own.has(e)) free.add(e);
            return;
        }
        if (!Array.isArray(e)) return;
        const exprs = parts(e).exprs;
        let last: symbol[] | null = null;
        for (const [, names] of exprs) if (names !== last) for (const name of last = names) own.add(name);
        for (const [x] of exprs) todo.add(x);
    });
    return [...free];
};

// the names of `scope` used in `e`
const freeIn = (ast: any, scope: ReadonlySet<symbol>): Set<symbol> => {
    const out = new Set<symbol>();
    const todo = new Worklist();
    todo.add(ast);
    todo.run(e => {
        if (typeof e === "symbol") {
            if (scope.has(e)) out.add(e);
        } else if (Array.isArray(e)) todo.addAll(subExprs(e));
    });
    return out;
};

// `e` with the uses of the names in `map` replaced, and the calls in `extra` given their extra arguments
const rewrite = (ast: any, map: ReadonlyMap<symbol, symbol>, extra: ReadonlyMap<any[], symbol[]>): any =>
    mapTree(Lsrc, ast, e => typeof e === "symbol" ? map.get(e) ?? e : formOrAtom(e), (next, e) => {
        const added = extra.get(e);
        if (added === undefined) return next;
        const at = calleeAt(e);
        return [...next.slice(0, at + 1), ...added.map(a => map.get(a) ?? a), ...next.slice(at + 1)];
    }, true);

// `e` with the calls in `map` calling the name given for them instead
const replaceCalls = (ast: any, map: ReadonlyMap<any[], symbol>): any =>
    map.size === 0 ? ast : mapTree(Lsrc, ast, formOrAtom, (next, e) => map.has(e) ? [next[0], next[1], map.get(e), ...next.slice(3)] : next, true);

const MAKE_CASE_LAMBDA = Symbol.for("%make-case-lambda");

// A %lambda of several clauses bound by a %let, %let* or %letrec to a name never assigned: each clause gets a name of its
// own (a %lambda of one, in a %letrec, so lifting applies to it), and every call of the name with a count a clause takes
// calls that clause. The procedure itself is only made (from the clauses, %make-case-lambda) if the name is still used
// some other way
export const splitCaseLambdas = (ast: any): any => {
    const assigned = assignedNames(ast);
    const isCandidate = (b: [symbol, any]) => isLambda(b[1]) && b[1].length > 3 && !assigned.has(b[0]);
    // the clauses of `name`'s case-lambda, the calls in `within` resolved to them, and whether the procedure is still needed
    const split = (name: symbol, caseLambda: any[], within: any[]) => {
        const clauses = clausesOf(caseLambda);
        const names = clauses.map(() => Symbol(name.description));
        const uses = usesOf(within, name);
        const map = new Map<any[], symbol>();
        let needed = uses.other;
        for (const node of uses.calls) {
            const i = clauses.findIndex(c => accepts(c, node.length - 3));
            if (i === -1) needed = true;
            else map.set(node, names[i]);
        }
        const bindings: [symbol, any][] = clauses.map((c, i) => [names[i], [CORE_LAMBDA, caseLambda[1], c]]);
        const procedure: [symbol, any][] = needed ? [[name, [CORE_INTCALL, null, MAKE_CASE_LAMBDA, ...names]]] : [];
        return { bindings, procedure, map };
    };
    // `e`, a %let, %let* or %letrec whose inits and body are already done, with its candidates split
    const splitIn = (e: any[]): any[] => {
        const op = e[0];
        const bindings: [symbol, any][] = e[2];
        const at = bindings.findIndex(isCandidate);
        if (at === -1) return e;
        const [name, caseLambda] = bindings[at];
        const body = e.slice(3);
        // where the name is in scope: every init of a %letrec, the later ones of a %let*, and the body
        const within = op === CORE_LETREC ? [...bindings.map(b => b[1]), ...body]
            : op === CORE_LET_STAR ? [...bindings.slice(at + 1).map(b => b[1]), ...body]
            : body;
        const { bindings: clauses, procedure, map } = split(name, caseLambda, within);
        const fix = (x: any) => replaceCalls(x, map);
        if (op === CORE_LETREC) {
            const rest = bindings.filter((_, i) => i !== at).map(b => [b[0], fix(b[1])] as [symbol, any]);
            const own = clauses.map(([n, c]) => [n, fix(c)] as [symbol, any]);
            return splitIn([CORE_LETREC, e[1], [...rest.slice(0, at), ...own, ...procedure, ...rest.slice(at)], ...body.map(fix)]);
        }
        if (op === CORE_LET) {
            const rest = [...bindings.slice(0, at), ...procedure, ...bindings.slice(at + 1)];
            return [CORE_LETREC, e[1], clauses, splitIn([CORE_LET, null, rest, ...body.map(fix)])];
        }
        const after = [...procedure, ...bindings.slice(at + 1).map(b => [b[0], fix(b[1])] as [symbol, any])];
        const inner = [CORE_LETREC, at === 0 ? e[1] : null, clauses, splitIn([CORE_LET_STAR, null, after, ...body.map(fix)])];
        return at === 0 ? inner : [CORE_LET_STAR, e[1], bindings.slice(0, at), inner];
    };
    return mapTree(Lsrc, ast, formOrAtom, done => done[0] === CORE_LET || done[0] === CORE_LETREC || done[0] === CORE_LET_STAR ? splitIn(done) : done, true);
};

const CALL_EC = Symbol.for("%call/ec");
const CALL_CC = Symbol.for("%call/cc");
const VALUES = Symbol.for("%values");

// (%call/ec (%lambda (k) body ...)) or the same with %call/cc, where k is never assigned and only ever called in the
// body itself (not in a lambda inside it, nor passed on or kept as a value): k can then only be called while the call is
// still running, so every call of it is an escape out of the body, whichever continuation it is. The body becomes a
// %block and each (k v ...) an %escape to it, a jump. A continuation captured in the body and resumed later resumes the
// frame the block is in, so an escape there still lands where k would return to
export const blockEscapes = (ast: any): any => {
    const assigned = assignedNames(ast);
    // whether every use of k in e is a call outside any lambda
    const onlyCalled = (body: readonly any[], k: symbol): boolean => {
        let only = true;
        const todo = new Worklist<boolean>();
        todo.addAll(body, false);
        todo.run((e, inLambda) => {
            if (e === k) only = false;
            else if (Array.isArray(e)) {
                const nested = inLambda || e[0] === CORE_LAMBDA;
                const exprs = subExprs(e);
                if (!isCallOf(e, k)) todo.addAll(exprs, nested);
                else if (nested) only = false;
                else for (let i = 1; i < exprs.length; i++) todo.add(exprs[i], nested);
            }
            if (!only) todo.stop();
        });
        return only;
    };
    const toEscapes = (ast: any, k: symbol, label: symbol): any => mapTree(Lsrc, ast, formOrAtom, (next, e) => {
        if (!isCallOf(e, k)) return next;
        const args = next.slice(3);
        return [CORE_ESCAPE, e[1], label, args.length === 1 ? args[0] : [CORE_INTCALL, null, VALUES, ...args]];
    }, true);
    return mapTree(Lsrc, ast, formOrAtom, done => {
        if (done[0] !== CORE_INTCALL || (done[2] !== CALL_EC && done[2] !== CALL_CC) || done.length !== 4) return done;
        const proc = done[3];
        if (!isSingleLambda(proc) || paramsOf(only(proc)).length !== 1 || restOf(only(proc)) !== null) return done;
        const k: symbol = paramsOf(only(proc))[0];
        const body = bodyOf(only(proc));
        if (assigned.has(k) || !onlyCalled(body, k)) return done;
        const label = Symbol(k.description);
        return [CORE_BLOCK, done[1], label, ...body.map((x: any) => toEscapes(x, k, label))];
    }, true);
};

// the lifting itself (see the top of this file)
export const liftLambdas = (ast: any): any => {
    const assigned = assignedNames(ast);

    const locals = boundNames(ast);

    // the context, `unsafe`: the local names that may not have their value yet when code there runs (%letrec values),
    // which a copy would miss, so they cannot be passed
    type Letrec = { inInits: ReadonlySet<symbol>, afterInits: ReadonlySet<symbol> };
    const visitor = new Visitor<ReadonlySet<symbol>, any>(
        formOrAtom,
        f => {
            const e = f.e;
            f.kids = subExprs(e);
            if (e[0] !== CORE_LETREC) return;
            const bindings: [symbol, any][] = e[2];
            const names = bindings.map(b => b[0]);
            const lambdas = new Set(names.filter((_, i) => isSingleLambda(bindings[i][1])));
            const values = names.filter(n => !lambdas.has(n));
            // the values' inits run before some values have theirs; if they may run the lambdas, so may everything else
            const runsEarly = bindings.some(b => !isSingleLambda(b[1]) && freeIn(b[1], lambdas).size > 0);
            const inInits = values.length === 0 ? f.ctx : new Set([...f.ctx, ...values]);
            f.state = { inInits, afterInits: runsEarly ? inInits : f.ctx } satisfies Letrec;
        },
        f => {
            const next = rebuild(Lsrc, f.e, f.out);
            return f.state === undefined ? next : liftIn(next, (f.state as Letrec).afterInits);
        },
        (f, i) => {
            const { inInits, afterInits } = f.state as Letrec, bindings: [symbol, any][] = f.e[2];
            return i < bindings.length && !isSingleLambda(bindings[i][1]) ? inInits : afterInits;
        },
    );

    const liftIn = (letrec: any[], unsafe: ReadonlySet<symbol>): any[] => {
        const bindings: [symbol, any][] = letrec[2];
        const body = letrec.slice(3);
        const names = bindings.map(b => b[0]);
        const inits = new Map<symbol, any>(bindings);
        const within = [...bindings.map(b => b[1]), ...body];

        let lifted = new Set(names.filter(n => isSingleLambda(inits.get(n)) && !assigned.has(n)));
        if (lifted.size === 0) return letrec;
        const usesOfEach = usesOfAll(within, lifted);
        let fv = new Map<symbol, symbol[]>();
        let calls = new Map<symbol, Uses["calls"]>();
        for (;;) {
            calls = new Map();
            const next = new Set<symbol>();
            for (const name of lifted) {
                const uses = usesOfEach.get(name)!;
                if (uses.other || uses.calls.some((c: any[]) => !accepts(only(inits.get(name)), c.length - calleeAt(c) - 1))) continue;
                next.add(name);
                calls.set(name, uses.calls);
            }
            // what each passes: its free locals (lifted ones it calls included), then what those need, to a fixpoint
            fv = new Map([...next].map(name => [name, freeLocals(only(inits.get(name)), locals)]));
            for (let changed = true; changed;) {
                changed = false;
                for (const vars of fv.values()) {
                    for (const v of [...vars]) {
                        for (const w of fv.get(v) ?? []) {
                            if (!vars.includes(w)) {
                                vars.push(w);
                                changed = true;
                            }
                        }
                    }
                }
            }
            // an assigned or not yet known variable cannot be passed, and a call must see the variables it passes as they are here
            for (const name of [...next]) {
                const vars = fv.get(name)!;
                if (vars.some(v => assigned.has(v) || unsafe.has(v))) next.delete(name);
            }
            if (next.size === lifted.size) break;
            lifted = next;
        }
        if (lifted.size === 0) return letrec;

        const extra = new Map<any[], symbol[]>();
        for (const name of lifted) for (const c of calls.get(name)!) extra.set(c, fv.get(name)!);
        const liftedInit = (name: symbol): any[] => {
            const lambda = inits.get(name);
            const c = only(lambda);
            const vars = fv.get(name)!;
            const renamed = new Map(vars.map(v => [v, Symbol(v.description)]));
            const newBody = bodyOf(c).map((x: any) => rewrite(x, renamed, extra));
            return [CORE_LAMBDA, lambda[1], clause(optionsOf(c), [...vars.map(v => renamed.get(v)!), ...paramsOf(c)], restOf(c), newBody)];
        };
        const newBindings = bindings.map(b => [b[0], lifted.has(b[0]) ? liftedInit(b[0]) : rewrite(b[1], new Map(), extra)]);
        const newBody = body.map(x => rewrite(x, new Map(), extra));
        return [CORE_LETREC, letrec[1], newBindings, ...newBody];
    };

    return visitor.visit(ast, new Set());
};
